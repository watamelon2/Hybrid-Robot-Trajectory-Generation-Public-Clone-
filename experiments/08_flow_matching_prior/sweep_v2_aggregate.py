"""Aggregate sweep_v2 results into a single Markdown report.

Usage: python sweep_v2_aggregate.py <sweep_dir>

Reads all phase{0,1,2,3,4}*/summary.json (and phase0_*.json), produces
``<sweep_dir>/v2_sweep_report.md``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def _safe_load(path: Path) -> dict | list | None:
    try:
        return json.loads(path.read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        return None


def _format_summary_row(r: dict, extra_cols: list[str]) -> str:
    """Format a single phase summary row as a Markdown table line."""
    cells = [
        f"{r.get('lambda_prior', '?')}",
        f"{r.get('n_success', 0)}/{r.get('n_total', 0)}",
        f"{r.get('success_rate', 0) * 100:.1f}%",
        f"{r.get('wall_s', 0):.0f}s",
    ]
    for col in extra_cols:
        cells.append(f"{r.get(col, '?')}")
    return "| " + " | ".join(cells) + " |"


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: sweep_v2_aggregate.py <sweep_dir>")
    sweep_dir = Path(sys.argv[1]).resolve()
    if not sweep_dir.exists():
        raise SystemExit(f"sweep dir not found: {sweep_dir}")

    lines: list[str] = []
    lines.append(f"# v_theta_v2 sweep report")
    lines.append(f"")
    lines.append(f"Sweep dir: `{sweep_dir.name}`")
    lines.append(f"")
    lines.append(f"This document is auto-generated by")
    lines.append(f"`experiments/08_flow_matching_prior/sweep_v2_aggregate.py`.")
    lines.append(f"")

    # ---- Phase 0 -----------------------------------------------------------
    lines.append(f"## Phase 0: prior-only replay (no MBD)")
    lines.append(f"")
    p0 = _safe_load(sweep_dir / "phase0_prior_only_replay.json")
    if p0 is None:
        lines.append("Phase 0 not run yet.")
    else:
        n_succ = p0.get("n_success", 0)
        n_total = p0.get("n_total", 0)
        rate = p0.get("success_rate", 0)
        lines.append(
            f"- Replays prior-sampled warm-starts directly through robosuite "
            f"without MBD.  Tests whether the v_theta_v2 prior is "
            f"*task-capable* on its own."
        )
        lines.append("")
        lines.append(f"**Result: {n_succ}/{n_total} = {rate*100:.1f}%**")
        if n_succ == 0:
            lines.append("")
            lines.append(
                f"> The flow prior alone produces 0 successful trajectories. "
                f"Any λ_prior > 0 must therefore drive MBD *into* a success "
                f"region; the warm-start cannot get us there.")
        else:
            lines.append("")
            lines.append(
                f"> The flow prior alone produces {n_succ} successful trajectories. "
                f"MBD's job is then to amplify these wins and recover them after "
                f"perturbation.")
    lines.append("")

    # ---- Phase 1 -----------------------------------------------------------
    lines.append(f"## Phase 1: λ_prior sweep WITH warm-start")
    lines.append(f"")
    lines.append(
        f"Same v_theta_v2 ckpt; warm-start = `prior.sample_initial_mean(s0)`. "
        f"`λ=0` means MBD refines from the prior warm-start without any "
        f"score-bridge.  Increasing λ adds the prior gradient term.  "
        f"Paired noise across λ values (exp07 design).")
    lines.append("")
    p1 = _safe_load(sweep_dir / "phase1_lambda_sweep_warmstart" / "summary.json")
    if p1 is None:
        lines.append("Phase 1 not run yet.")
    else:
        lines.append("| λ_prior | succ | rate | wall |")
        lines.append("|---|---|---|---|")
        p1_sorted = sorted(p1, key=lambda r: r["lambda_prior"])
        for r in p1_sorted:
            lines.append(_format_summary_row(r, []))
        best = max(p1, key=lambda r: (r["n_success"], -r["lambda_prior"]))
        lines.append("")
        lines.append(
            f"**Best in Phase 1: λ={best['lambda_prior']} → "
            f"{best['n_success']}/{best['n_total']} = "
            f"{best['success_rate']*100:.1f}%**")
    lines.append("")

    # ---- Phase 2 -----------------------------------------------------------
    lines.append(f"## Phase 2: λ_prior sweep WITHOUT warm-start")
    lines.append(f"")
    lines.append(
        f"Initial mean = zeros (no prior warm-start).  `λ=0` is the "
        f"vanilla MBD baseline at our config (H=120, K=10, M=16, σ_max=0.5).  "
        f"Higher λ tests whether the flow score-bridge can push MBD toward "
        f"success starting from zero.")
    lines.append("")
    p2 = _safe_load(sweep_dir / "phase2_lambda_sweep_no_warmstart" / "summary.json")
    if p2 is None:
        lines.append("Phase 2 not run yet.")
    else:
        lines.append("| λ_prior | succ | rate | wall |")
        lines.append("|---|---|---|---|")
        p2_sorted = sorted(p2, key=lambda r: r["lambda_prior"])
        for r in p2_sorted:
            lines.append(_format_summary_row(r, []))
    lines.append("")

    # ---- Phase 3 -----------------------------------------------------------
    lines.append(f"## Phase 3: best-λ + K-extension")
    lines.append(f"")
    lines.append(
        f"Holds best λ from Phase 1, increases K (denoising iterations).  "
        f"Tests whether more MBD refinement at the best λ value finds success.")
    lines.append("")
    p3 = _safe_load(sweep_dir / "phase3_best_lambda_K_extension" / "summary.json")
    if p3 is None:
        lines.append("Phase 3 not run yet.")
    else:
        lines.append("| K | λ_prior | succ | rate | wall |")
        lines.append("|---|---|---|---|---|")
        p3_sorted = sorted(p3, key=lambda r: (r.get("K", 0), r["lambda_prior"]))
        for r in p3_sorted:
            cells = [
                f"{r.get('K', '?')}",
                f"{r.get('lambda_prior', '?')}",
                f"{r.get('n_success', 0)}/{r.get('n_total', 0)}",
                f"{r.get('success_rate', 0)*100:.1f}%",
                f"{r.get('wall_s', 0):.0f}s",
            ]
            lines.append("| " + " | ".join(cells) + " |")
    lines.append("")

    # ---- Phase 4 -----------------------------------------------------------
    lines.append(f"## Phase 4: best-λ + σ_max sweep")
    lines.append(f"")
    lines.append(
        f"Holds best λ from Phase 1, decreases σ_max.  Smaller σ_max keeps "
        f"the M perturbations closer to the warm-start, preserving any "
        f"good structure in the prior's initial guess.")
    lines.append("")
    p4 = _safe_load(sweep_dir / "phase4_best_lambda_sigma_sweep" / "summary.json")
    if p4 is None:
        lines.append("Phase 4 not run yet.")
    else:
        lines.append("| σ_max | λ_prior | succ | rate | wall |")
        lines.append("|---|---|---|---|---|")
        p4_sorted = sorted(p4, key=lambda r: (r.get("sigma_max", 0), r["lambda_prior"]))
        for r in p4_sorted:
            cells = [
                f"{r.get('sigma_max', '?')}",
                f"{r.get('lambda_prior', '?')}",
                f"{r.get('n_success', 0)}/{r.get('n_total', 0)}",
                f"{r.get('success_rate', 0)*100:.1f}%",
                f"{r.get('wall_s', 0):.0f}s",
            ]
            lines.append("| " + " | ".join(cells) + " |")
    lines.append("")

    # ---- Phase 5 -----------------------------------------------------------
    lines.append(f"## Phase 5: σ-preservation × λ cross sweep")
    lines.append(f"")
    lines.append(
        f"Driven by Phase 0's finding (prior-only = 8.3 %): default σ_max=0.5 "
        f"is destroying the prior's good warm-starts.  Phase 5 sweeps "
        f"σ_max ∈ {{0.02, 0.05, 0.1}} crossed with λ ∈ {{0.0, 0.1, 0.5}}.  "
        f"Each σ_max cell uses paired noise across λ values.")
    lines.append("")
    p5 = _safe_load(sweep_dir / "phase5_sigma_preservation" / "summary.json")
    if p5 is None:
        lines.append("Phase 5 not run yet.")
    else:
        lines.append("| σ_max | λ_prior | succ | rate | wall |")
        lines.append("|---|---|---|---|---|")
        p5_sorted = sorted(p5, key=lambda r: (r.get("sigma_max", 0), r["lambda_prior"]))
        for r in p5_sorted:
            cells = [
                f"{r.get('sigma_max', '?')}",
                f"{r.get('lambda_prior', '?')}",
                f"{r.get('n_success', 0)}/{r.get('n_total', 0)}",
                f"{r.get('success_rate', 0)*100:.1f}%",
                f"{r.get('wall_s', 0):.0f}s",
            ]
            lines.append("| " + " | ".join(cells) + " |")
        if p5:
            best = max(p5, key=lambda r: (r["n_success"], -r["lambda_prior"]))
            lines.append("")
            lines.append(
                f"**Best in Phase 5: σ_max={best.get('sigma_max', '?')}, "
                f"λ={best['lambda_prior']} → "
                f"{best['n_success']}/{best['n_total']} = "
                f"{best['success_rate']*100:.1f}%**")
    lines.append("")

    # ---- Phase 6 -----------------------------------------------------------
    lines.append(f"## Phase 6: best (σ_max, λ) + K=20")
    lines.append(f"")
    lines.append(
        f"Holds best (σ_max, λ) from Phase 5, increases K from 10 → 20.  "
        f"Tests whether more refinement iterations at the preservation-friendly "
        f"σ amplifies the wins.")
    lines.append("")
    p6 = _safe_load(sweep_dir / "phase6_best_k_extension" / "summary.json")
    if p6 is None:
        lines.append("Phase 6 not run yet.")
    elif not p6:
        lines.append("Phase 6 skipped (Phase 5 best was not above Phase 0 baseline).")
    else:
        lines.append("| λ_prior | succ | rate | wall |")
        lines.append("|---|---|---|---|")
        for r in p6:
            lines.append(_format_summary_row(r, []))
    lines.append("")

    # ---- Phase 7 -----------------------------------------------------------
    lines.append(f"## Phase 7: bridge=quadratic at Phase-5 best σ")
    lines.append(f"")
    lines.append(
        f"Contingency for the score-bridge formula bug.  Phase 1-6 all used "
        f"the linear bridge `score = (t * x1_hat - x) / (1 - t)`; the "
        f"theoretical bridge under linear-interp + N(0, I) noising has a "
        f"quadratic denominator `(1 - t)^2`.  At σ_max=0.02 the linear "
        f"bridge collapses every λ>0 cell from 10/60 → 2/60, consistent with "
        f"the prior gradient being under-weighted near t≈1.  Phase 7 re-runs "
        f"σ_max=0.02 with `--bridge-formula quadratic` at λ ∈ {{0.1, 0.5, 1.0}} "
        f"to test whether the corrected bridge unlocks a positive λ "
        f"contribution.")
    lines.append("")
    p7 = _safe_load(sweep_dir / "phase7_bridge_quadratic" / "summary.json")
    if p7 is None:
        lines.append("Phase 7 not run yet.")
    elif not p7:
        lines.append("Phase 7 produced no rows.")
    else:
        lines.append("| λ_prior | succ | rate | wall |")
        lines.append("|---|---|---|---|")
        for r in p7:
            lines.append(_format_summary_row(r, []))
        best = max(p7, key=lambda r: r["n_success"])
        lines.append("")
        lines.append(
            f"**Best in Phase 7: λ={best['lambda_prior']} → "
            f"{best['n_success']}/{best['n_total']} = "
            f"{best['success_rate']*100:.1f}%**")
    lines.append("")

    # ---- Bottom line ------------------------------------------------------
    lines.append(f"## Bottom line")
    lines.append(f"")
    best_overall: dict | None = None
    best_label = ""
    # Treat Phase 0 (prior-only) as a baseline candidate too.
    if p0 is not None:
        best_overall = {
            "n_success": p0.get("n_success", 0),
            "n_total": p0.get("n_total", 0),
            "success_rate": p0.get("success_rate", 0),
            "lambda_prior": "n/a (prior-only)",
        }
        best_label = "Phase 0"
    for label, phase in [
        ("Phase 1", p1), ("Phase 2", p2), ("Phase 3", p3),
        ("Phase 4", p4), ("Phase 5", p5), ("Phase 6", p6),
        ("Phase 7", p7),
    ]:
        if not phase:
            continue
        for r in phase:
            if best_overall is None or r["n_success"] > best_overall["n_success"]:
                best_overall = r
                best_label = label
    if best_overall is None:
        lines.append("No completed phase yet.")
    elif best_overall["n_success"] == 0:
        lines.append(
            f"**v_theta_v2 + MBD remains at 0/60 across all swept configurations.**")
        lines.append("")
        lines.append(
            f"This is a strong negative result.  Either:"
        )
        lines.append(
            f"- The v2 architecture, while structurally correct on the "
            f"diagnostic tests (norm/step, pairwise-across-demos, d2real), "
            f"is not producing the *direction* needed for PickPlaceCan."
        )
        lines.append(
            f"- The MBD score-bridge formulation `(t*v - x)/(1-t)` from "
            f"`adapter.py:147` is the wrong scoring of the prior's velocity "
            f"field for the actual MBD update equation."
        )
        lines.append(
            f"- The H=120 / M=16 / K=10 envelope is fundamentally too narrow "
            f"for any prior on this task (consistent with exp 04 = 0/60 "
            f"and exp 15's K×R grid maxing at 8.3%).")
    else:
        lines.append(
            f"**Best v_theta_v2 + MBD configuration: "
            f"{best_label} at λ={best_overall['lambda_prior']} → "
            f"{best_overall['n_success']}/{best_overall['n_total']} = "
            f"{best_overall['success_rate']*100:.1f}%**")
        lines.append("")
        lines.append(
            f"This is a positive result that breaks the v1+v2 0/60 ceiling.  "
            f"Detailed cost-curves and per-rollout breakdowns live in the "
            f"per-phase directories.")
    lines.append("")

    report_path = sweep_dir / "v2_sweep_report.md"
    report_path.write_text("\n".join(lines))
    print(f"wrote {report_path}")


if __name__ == "__main__":
    main()
